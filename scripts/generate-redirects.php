<?php
/**
 * Generates redirects.xml, the list of manual pages that moved from the main
 * manual (php/doc-en and its translations) to this manual.
 *
 * Every page keeps its xml:id, so an old URL such as
 * /manual/fr/function.apcu-add.php maps to /manual/extensions/function.apcu-add.php.
 * The list is a snapshot taken at migration time: only pages that existed in
 * the main manual are listed, so URLs that never existed are not redirected.
 * The summaries in language/ are not listed either, they live in the main
 * manual.
 *
 * A page is listed when all of the following hold:
 *   - it is rendered by PhD (a <id>.php file in --pages),
 *   - its xml:id is declared under reference/ in this repository,
 *   - its xml:id was declared for the same extension in the main manual.
 *
 * Usage
 *   php scripts/generate-redirects.php --pages=PATH --doc-en=PATH [--rev=REV] [--output=FILE]
 *   --pages    directory holding the rendered pages (output/php-web)
 *   --doc-en   a checkout of php/doc-en holding reference/<extension>/
 *   --rev      read the main manual from this revision of --doc-en instead of
 *              its working tree (e.g. origin/master)
 *   --output   file to write, defaults to redirects.xml in the repository root
 *
 * Exit status: 0 on success, 1 on any error.
 */

declare(strict_types=1);

ini_set('display_errors', '1');
error_reporting(E_ALL);

$options = getopt('', ['pages:', 'doc-en:', 'rev:', 'output:', 'help']);
if (isset($options['help']) || !isset($options['pages'], $options['doc-en'])) {
    fwrite(STDERR, "Usage: php scripts/generate-redirects.php --pages=PATH --doc-en=PATH [--rev=REV] [--output=FILE]\n");
    exit(isset($options['help']) ? 0 : 1);
}

$root = dirname(__DIR__);
$pagesDir = rtrim((string) $options['pages'], '/');
$docEn = rtrim((string) $options['doc-en'], '/');
$rev = isset($options['rev']) ? (string) $options['rev'] : null;
$output = (string) ($options['output'] ?? $root . '/redirects.xml');

foreach ([$pagesDir, $docEn, $root . '/reference'] as $dir) {
    if (!is_dir($dir)) {
        fwrite(STDERR, "Not a directory: $dir\n");
        exit(1);
    }
}

/**
 * @return list<string> the xml:id values found in the given XML text
 */
function xmlIds(string $xml): array
{
    preg_match_all('/xml:id="([^"]+)"/', $xml, $matches);

    return $matches[1];
}

/**
 * @return array<string, true> every xml:id declared in the .xml files under a directory
 */
function idsInDirectory(string $dir): array
{
    $ids = [];
    $files = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($dir, FilesystemIterator::SKIP_DOTS));
    foreach ($files as $file) {
        if ($file->isFile() && $file->getExtension() === 'xml') {
            foreach (xmlIds((string) file_get_contents($file->getPathname())) as $id) {
                $ids[$id] = true;
            }
        }
    }

    return $ids;
}

/**
 * @return array<string, true> every xml:id declared by a path of a git revision
 */
function idsInRevision(string $repository, string $rev, string $path): array
{
    $command = sprintf(
        'git -C %s grep -h -o %s %s -- %s 2>/dev/null',
        escapeshellarg($repository),
        escapeshellarg('xml:id="[^"]*"'),
        escapeshellarg($rev),
        escapeshellarg($path),
    );
    $ids = [];
    foreach (xmlIds((string) shell_exec($command)) as $id) {
        $ids[$id] = true;
    }

    return $ids;
}

$extensions = array_values(array_filter(
    scandir($root . '/reference') ?: [],
    static fn (string $name): bool => $name[0] !== '.' && is_dir($root . '/reference/' . $name),
));

$new = idsInDirectory($root . '/reference');

$old = [];
foreach ($extensions as $extension) {
    $old += $rev === null
        ? idsInDirectory($docEn . '/reference/' . $extension)
        : idsInRevision($docEn, $rev, 'reference/' . $extension);
}

$pages = [];
foreach (glob($pagesDir . '/*.php') ?: [] as $file) {
    $pages[basename($file, '.php')] = true;
}

$ids = array_keys(array_intersect_key($pages, $new, $old));
sort($ids, SORT_STRING);

if ($ids === []) {
    fwrite(STDERR, "No page to redirect: check --pages and --doc-en.\n");
    exit(1);
}

$xml = <<<'XML'
<?xml version="1.0" encoding="utf-8"?>
<?do-not-translate?>
<!--
 Manual pages of the extensions that moved from the main manual to this one.

 Generated by scripts/generate-redirects.php, do not edit by hand.
 Rendered to redirects.json by PhD. A page keeps its name, so the main manual
 serves every request of /manual/{lang}/{from}.php as a 301 redirect to
 /manual/extensions/{to}.php.
-->
<redirects>

 <group scope="in-manual">

XML;

// The main manual lowercases the requested page name before looking it up,
// while a few xml:id values (pool.submitTo) are mixed case. The key is
// lowercase, the target keeps the case of the rendered page.
$redirects = [];
foreach ($ids as $id) {
    $from = strtolower($id);
    if (isset($redirects[$from])) {
        fwrite(STDERR, "Two pages differ only by case: {$redirects[$from]}, $id\n");
        exit(1);
    }
    $redirects[$from] = $id;
}
ksort($redirects, SORT_STRING);

foreach ($redirects as $from => $to) {
    $xml .= sprintf("  <redirect from=\"%s\" to=\"%s\"/>\n", $from, $to);
}

$xml .= "\n </group>\n\n</redirects>\n";

if (file_put_contents($output, $xml) === false) {
    fwrite(STDERR, "Could not write $output\n");
    exit(1);
}

fprintf(STDOUT, "%d redirects written to %s\n", count($ids), $output);
